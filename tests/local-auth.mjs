import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createClient } from '@supabase/supabase-js';

// Local test accounts only; never run this against a remote Supabase project.
const api = 'http://127.0.0.1:55421';
const app = 'http://127.0.0.1:3347';
const { LOCAL_ANON_KEY: anon, LOCAL_SERVICE_ROLE_KEY: service } = process.env;
assert.ok(anon && service, 'Set local keys from supabase status');
const admin = createClient(api, service, { auth: { persistSession: false } });
const client = createClient(api, anon, { auth: { persistSession: false } });
const email = `sprint0-${randomUUID()}@example.test`;
const password = `Test-${randomUUID()}`;
let id;
let invitedId;
try {
  const signup = await client.auth.signUp({ email, password });
  assert.ok(signup.error, 'public signup must be disabled');
  const inviteEmail = `invite-${randomUUID()}@example.test`;
  const invited = await admin.auth.admin.inviteUserByEmail(inviteEmail);
  assert.ifError(invited.error);
  invitedId = invited.data.user.id;
  const mailbox = await (await fetch('http://127.0.0.1:55424/api/v1/messages')).json();
  const message = mailbox.messages.find((item) => item.To.some((recipient) => recipient.Address === inviteEmail));
  assert.ok(message, 'invitation email delivered to local mailbox');
  const mailResponse = await fetch(`http://127.0.0.1:55424/api/v1/message/${message.ID}`);
  assert.equal(mailResponse.status, 200);
  const mail = await mailResponse.json();
  const html = mail.HTML;
  const otp = html.match(/<strong>(\d{6})<\/strong>/)?.[1];
  assert.ok(otp, 'invitation email contains OTP');
  assert.ok(!html.includes('token_hash='), 'invitation URL contains no token');
  const invitePage = await fetch(`${app}/invite`);
  assert.equal(invitePage.status, 200);
  const inviteAction = (await invitePage.text()).match(/name="(\$ACTION_ID_[^"]+)"/);
  assert.ok(inviteAction);
  const inviteForm = new FormData();
  inviteForm.set(inviteAction[1], ''); inviteForm.set('email', inviteEmail); inviteForm.set('code', otp);
  const accepted = await fetch(`${app}/invite`, { method: 'POST', body: inviteForm, redirect: 'manual' });
  assert.equal(accepted.status, 303);
  assert.equal(accepted.headers.get('location'), '/set-password');
  const reused = await fetch(`${app}/invite`, { method: 'POST', body: inviteForm, redirect: 'manual' });
  assert.equal(reused.status, 303);
  assert.equal(reused.headers.get('location'), '/invite?error=invalid');
  const inviteCookie = accepted.headers.getSetCookie().map((s) => s.split(';')[0]).join('; ');
  const passwordPage = await fetch(`${app}/set-password`, { headers: { cookie: inviteCookie } });
  assert.equal(passwordPage.status, 200);
  const passwordAction = (await passwordPage.text()).match(/name="(\$ACTION_ID_[^"]+)"/);
  assert.ok(passwordAction);
  const passwordForm = new FormData();
  passwordForm.set(passwordAction[1], ''); passwordForm.set('password', password); passwordForm.set('confirmation', password);
  const passwordSet = await fetch(`${app}/set-password`, { method: 'POST', body: passwordForm, headers: { cookie: inviteCookie }, redirect: 'manual' });
  assert.equal(passwordSet.status, 303);
  assert.equal(passwordSet.headers.get('location'), '/profile');
  const created = await admin.auth.admin.createUser({ email, password, email_confirm: true });
  assert.ifError(created.error);
  id = created.data.user.id;
  const directLogin = await client.auth.signInWithPassword({ email, password });
  assert.ifError(directLogin.error);
  const loginPage = await fetch(`${app}/login`);
  assert.equal(loginPage.status, 200);
  const action = (await loginPage.text()).match(/name="(\$ACTION_ID_[^"]+)"/);
  assert.ok(action, 'login form action');
  const form = new FormData();
  form.set(action[1], ''); form.set('email', email); form.set('password', password);
  const login = await fetch(`${app}/login`, { method: 'POST', body: form, redirect: 'manual' });
  assert.equal(login.status, 303);
  assert.equal(login.headers.get('location'), '/');
  const cookie = login.headers.getSetCookie().map((s) => s.split(';')[0]).join('; ');
  assert.ok(cookie, 'login sets a session cookie');
  const home = await fetch(`${app}/`, { headers: { cookie }, redirect: 'manual' });
  assert.equal(home.status, 307);
  assert.equal(home.headers.get('location'), '/profile');
  const profile = await fetch(`${app}/profile`, { headers: { cookie } });
  assert.equal(profile.status, 200);
  const profileAction = (await profile.text()).match(/name="(\$ACTION_ID_[^"]+)"/);
  assert.ok(profileAction);
  const update = new FormData();
  update.set(profileAction[1], ''); update.set('username', `u${id.replaceAll('-', '').slice(0, 12)}`); update.set('display_name', 'Test');
  const saved = await fetch(`${app}/profile`, { method: 'POST', body: update, headers: { cookie }, redirect: 'manual' });
  assert.equal(saved.status, 303);
  assert.equal(saved.headers.get('location'), '/');
  const welcome = await fetch(`${app}/`, { headers: { cookie } });
  assert.equal(welcome.status, 200);
  assert.match(await welcome.text(), /Benvenuto nei Ghepardi/);
  const disabled = await admin.from('profiles').update({ status: 'disabled' }).eq('id', id);
  assert.ifError(disabled.error);
  const revoked = await fetch(`${app}/`, { headers: { cookie }, redirect: 'manual' });
  assert.equal(revoked.status, 307);
  assert.equal(revoked.headers.get('location'), '/login?error=access');
  console.log('PASS: signup denied; invite, password setup, login, onboarding, protected page and revocation');
} finally {
  for (const userId of [id, invitedId].filter(Boolean)) {
    const removedProfile = await admin.from('profiles').delete().eq('id', userId);
    assert.ifError(removedProfile.error);
    const removedUser = await admin.auth.admin.deleteUser(userId);
    assert.ifError(removedUser.error);
  }
}
